-- Индекс для захвата порции (#166, #148). Запрос захвата выбирает события со списком состояний
-- (status IN ('NEW', 'IN_PROGRESS')) в порядке next_attempt_at, id. В индексе
-- idx_outbox_events_status_next_attempt записи упорядочены сначала по состоянию, и при двух
-- состояниях общий порядок по времени из него не взять: PostgreSQL читал все готовые события и
-- сортировал их, а при заторе — ещё и на диске.
--
-- Этот индекс частичный с тем же условием, что и у запроса захвата, и упорядочен ровно так, как
-- запрос сортирует. Поэтому захват идёт по индексу от самого давно ожидающего события и
-- останавливается, набрав порцию. id вторым ключом — события с одинаковым временем попытки
-- захватываются в одном и том же порядке (#148).
--
-- idx_outbox_events_status_next_attempt остаётся: по нему считаются события в каждом состоянии
-- для метрики crm.outbox.events, в том числе FAILED, которых в этом индексе нет.
CREATE INDEX idx_outbox_events_claim
    ON outbox_events (next_attempt_at, id) WHERE status IN ('NEW', 'IN_PROGRESS');

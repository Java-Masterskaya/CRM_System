-- Очередь работ оператора (T-052): его незавершённые заявки, сначала более приоритетные, при
-- равном приоритете — созданные раньше. Колонки — в порядке условий и сортировки запроса:
-- арендатор и исполнитель сравниваются на равенство, статус — список незавершённых или один из
-- них, затем приоритет по убыванию и время создания по возрастанию. Условия совпадают с
-- RequestQueueService — менять только вместе.
CREATE INDEX idx_requests_tenant_assignee_queue
    ON requests (tenant_id, assignee_id, status, priority_rank DESC, created_at);

-- Прежний индекс (tenant_id, assignee_id) — начало нового: все его запросы новый обслужит так же,
-- а держать два индекса значит дважды обновлять их при каждой записи заявки.
DROP INDEX idx_requests_tenant_assignee;

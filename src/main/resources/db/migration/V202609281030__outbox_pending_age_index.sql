-- Индекс для метрики возраста самого давнего недоставленного события (#154). Запрос
-- min(created_at) по одному состоянию берёт первую запись этого индекса, а не перебирает все
-- события в состоянии: без индекса запрос дорожает вместе с очередью — как раз при заторе,
-- когда метрика нужнее всего.
-- Без tenant_id: метрика считается по всей очереди сразу, как и захват порции
-- (idx_outbox_events_status_next_attempt).
CREATE INDEX idx_outbox_events_status_created_at ON outbox_events (status, created_at);

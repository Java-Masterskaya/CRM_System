-- Плановая очистка refresh-токенов (T-029): истёкшие и отозванные записи удаляются порциями.
-- Каждый обмен токена добавляет строку, поэтому таблица растёт с каждым входом и обменом, и без
-- индексов порцию на удаление пришлось бы искать перебором всей таблицы.
--
-- Истёкшие ищутся по сроку жизни. Отозванные — по частичному индексу: в нём только отозванные
-- строки, а действующие, которых большинство, его не утяжеляют. Условия совпадают с запросами
-- RefreshTokenRepository.purgeExpired и purgeRevoked — менять только вместе.
--
-- Индексы строятся под блокировкой записи в таблицу; сейчас она маленькая. Для большой таблицы
-- индекс строят заранее, вне миграции (CREATE INDEX CONCURRENTLY).
CREATE INDEX idx_refresh_tokens_expires_at
    ON refresh_tokens (expires_at);

CREATE INDEX idx_refresh_tokens_revoked
    ON refresh_tokens (revoked_at)
    WHERE revoked_at IS NOT NULL;

package ru.practicum.crm.request.domain;

/**
 * Значимые поля заявки: их изменения попадают в журнал аудита (ТЗ §6.7).
 *
 * <p>Это поля, которые правит администратор при разборе заявки (ТЗ §6.3: приоритет, срок, тип,
 * описание), и исполнитель — назначение тоже фиксируется в журнале (T-048). Сроки первого ответа
 * и решения попадают в журнал, когда их пересчитывает смена приоритета или типа (T-062).
 * Статуса здесь нет: переходы записываются в отдельную историю статусов (T-044).
 */
public enum AuditedField {
    PRIORITY,
    TYPE,
    DESIRED_DUE_AT,
    DESCRIPTION,
    ASSIGNEE,
    FIRST_RESPONSE_DUE_AT,
    RESOLUTION_DUE_AT
}

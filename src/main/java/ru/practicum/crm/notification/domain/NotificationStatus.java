package ru.practicum.crm.notification.domain;

/**
 * Результат последней попытки доставить уведомление.
 *
 * <p>{@link #FAILED} не значит «доставка прекращена»: повторять ли попытку, решает очередь
 * исходящих событий. Окончательный неуспех виден по событию в {@code outbox_events}.
 */
public enum NotificationStatus {

    /** Письмо принял почтовый сервер. */
    SENT,

    /** Письмо не удалось отправить; причина — в коде последней ошибки. */
    FAILED
}

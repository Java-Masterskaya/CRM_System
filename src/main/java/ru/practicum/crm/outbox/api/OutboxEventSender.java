package ru.practicum.crm.outbox.api;

/**
 * Доставляет события одного типа: письмом, вебхуком и так далее.
 *
 * <p>Реализации живут в пакетах, которые отвечают за канал доставки, поэтому интерфейс лежит
 * в {@code api}: по правилам границ (SPEC §2.3) другой пакет может опираться только на него.
 * Обработчик находит отправителя по типу события; если отправителя нет, попытка считается
 * неудачной.
 */
public interface OutboxEventSender {

    /** Тип событий, которые доставляет этот отправитель, — значение {@code event_type}. */
    String eventType();

    /**
     * Доставляет событие. Любое исключение — неудачная попытка: событие вернётся в очередь.
     * Вызывается вне транзакции, поэтому долгий ответ внешнего сервиса не держит соединение
     * с базой.
     *
     * <p>Гарантия доставки — «хотя бы один раз»: после сбоя то же событие может прийти снова,
     * с тем же {@link OutboxMessage#id()}.
     */
    void send(OutboxMessage message);
}

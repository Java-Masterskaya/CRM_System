package ru.practicum.crm.outbox.api;

import java.util.Map;
import java.util.UUID;

/**
 * Запись исходящего события из бизнес-операции (T-065, SPEC §3.5).
 *
 * <p>Событие записывается в таблицу исходящих в той же транзакции, что и само изменение, —
 * прямым вызовом, а не слушателем «после фиксации». Поэтому оно появляется ровно тогда, когда
 * изменение зафиксировано: откат операции убирает и событие, а падение приложения сразу после
 * фиксации его не теряет. Доставляет событие фоновый обработчик — отправителю, который объявил
 * этот тип ({@link OutboxEventSender#eventType()}).
 *
 * <p>Методы вызываются только внутри транзакции операции: без неё событие записалось бы отдельно
 * от изменения, поэтому такой вызов отклоняется исключением
 * {@code IllegalTransactionStateException}. Запись ничего не отправляет и никуда наружу не
 * обращается — внутри транзакции операции нет ни почты, ни других сервисов.
 *
 * <p>Полезная нагрузка хранится в JSON: значения — строки, числа, логические значения, списки и
 * вложенные таблицы из них. Нагрузка копируется, и после записи событие не меняется.
 */
public interface OutboxPublisher {

    /**
     * Записывает событие, не относящееся к конкретному объекту.
     *
     * @return идентификатор события; его же получит отправитель в {@link OutboxMessage#id()}
     * @throws IllegalArgumentException если не указан арендатор, тип события или полезная
     *     нагрузка либо тип длиннее 100 символов
     */
    UUID publish(UUID tenantId, String eventType, Map<String, Object> payload);

    /**
     * Записывает событие об объекте: {@code aggregateType} — вид объекта (например,
     * {@code REQUEST}), {@code aggregateId} — его идентификатор. По этой ссылке выбираются все
     * события одного объекта.
     *
     * @return идентификатор события; его же получит отправитель в {@link OutboxMessage#id()}
     * @throws IllegalArgumentException то же, что у {@link #publish(UUID, String, Map)}, а также
     *     если ссылка на объект задана не целиком или вид объекта длиннее 100 символов
     */
    UUID publish(UUID tenantId, String eventType, String aggregateType, UUID aggregateId,
            Map<String, Object> payload);
}

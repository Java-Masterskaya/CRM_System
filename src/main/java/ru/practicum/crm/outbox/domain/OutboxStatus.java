package ru.practicum.crm.outbox.domain;

/**
 * Состояние доставки исходящего события.
 *
 * <p>Переходы между состояниями выполняет фоновый обработчик (T-066, #88) и обработка
 * неуспеха (T-067, #89); здесь фиксируется только перечень.
 */
public enum OutboxStatus {

    /** Записано в одной транзакции с бизнес-операцией, ждёт доставки. */
    NEW,

    /** Взято обработчиком; защищает от повторной выдачи другому экземпляру приложения. */
    IN_PROGRESS,

    /** Доставлено. */
    SENT,

    /** Попытки исчерпаны; запись остаётся для разбора. */
    FAILED
}
